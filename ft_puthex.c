#include "ft_printf.h"

int	ft_puthex(unsigned int n, char format)
{
	char	*base;
	int		len;

	if (format == 'X')
		base = "0123456789ABCDEF";
	else
		base = "0123456789abcdef";
	len = 0;
	if (n >= 16)
		len += ft_puthex((n / 16), format);
	len += write(1, &base[n % 16], 1);
	return (len);
}
